from bs4 import BeautifulSoup
import requests
import json
import re
import os
import argparse


# --- Helpers ---

def get_id(link: str):
    return link.split('/')[-2]


def checkIfImageExistsInDirectory(image_name: str):
    return os.path.isfile('./web_assets/' + image_name)


def save_image(image_url: str, image_name: str):
    if checkIfImageExistsInDirectory(image_name):
        print('image already exists for id: {}'.format(image_name))
        return
    with open('./web_assets/' + image_name, 'wb') as handle:
        response = requests.get(image_url, stream=True)
        if not response.ok:
            print(response)
        for block in response.iter_content(1024):
            if not block:
                break
            handle.write(block)


def root_dir():
    """Returns the project root directory (two levels up from this script)."""
    return os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))


# --- Scrapers ---

def scrape_producers():
    """
    Scrape all anime producers/studios from MAL.
    Saves JSON to web_assets/ and generates Dart const map in lib/generated/.
    """
    url = 'https://myanimelist.net/anime/producer'
    print(f'[producers] Fetching {url} ...')
    soup = BeautifulSoup(requests.get(url).text, 'html.parser')

    producers = {}
    # Links are in the format: /anime/producer/ID/URL_Name
    for a in soup.select('a[href*="/anime/producer/"]'):
        href = a.get('href', '')
        match = re.search(r'/anime/producer/(\d+)/', href)
        if match:
            pid = match.group(1)
            # Display name is the link text, minus the count suffix like " (123)"
            name = re.sub(r'\s*\(\d[\d,]*\)\s*$', '', a.get_text(strip=True))
            if name and pid not in producers:
                producers[pid] = name

    # Save JSON
    json_path = os.path.join(root_dir(), 'web_assets', 'anime_producers.json')
    with open(json_path, 'w', encoding='utf-8') as f:
        json.dump(producers, f, ensure_ascii=False, indent=2)

    # Generate Dart file
    dart_path = os.path.join(root_dir(), 'lib', 'generated', 'anime_producers.dart')
    _generate_map_dart('animeStudios', producers, dart_path)
    print(f'[producers] Saved {len(producers)} producers to {dart_path}')
    return producers


