if __name__ == '__main__':
    parser = argparse.ArgumentParser(description='MAL data scraper')
    parser.add_argument('--producers', action='store_true', help='Scrape anime producers/studios')
    parser.add_argument('--magazines', action='store_true', help='Scrape manga magazines')
    parser.add_argument('--genres', action='store_true', help='Scrape anime & manga genres')
    parser.add_argument('--genre-desc', choices=['anime', 'manga'], help='Scrape genre descriptions & images')
    parser.add_argument('--all', action='store_true', help='Run all scrapers (producers, magazines, genres)')
    args = parser.parse_args()

    if args.all:
        scrape_producers()
        scrape_magazines()
        scrape_genres('anime')
        scrape_genres('manga')
    else:
        if args.producers:
            scrape_producers()
        if args.magazines:
            scrape_magazines()
        if args.genres:
            scrape_genres('anime')
            scrape_genres('manga')
        if args.genre_desc:
            genre_page(args.genre_desc)

    if not any(vars(args).values()):
        parser.print_help()